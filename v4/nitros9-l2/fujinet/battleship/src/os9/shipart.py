# shipart.py: the battleship of fnbattleship's title, as half-block pixel
# art (two pixels to a character cell, as fnweather's icons are).
#   python3 shipart.py c > shipart.h     the C data, for title.c
#   python3 shipart.py preview           shipart.ppm, to look at
# @license gpl v. 3, see fujinet/LICENSE for details.
import sys

W, H = 72, 20

# The palette: a letter to a color (title.c's color_of() has the same).
PAL = {'.': None, 'W': (255, 255, 255), 'w': (170, 170, 180), 'B': (85, 120, 255),
       'b': (20, 50, 170), 'C': (90, 240, 255), 'c': (0, 160, 180),
       'R': (255, 80, 80), 'r': (170, 20, 20), 'Y': (255, 235, 60), 'y': (190, 120, 20)}

def canvas(): return [['.'] * W for _ in range(H)]

def rect(c, x0, y0, x1, y1, col):
    for y in range(max(0, y0), min(H, y1)):
        for x in range(max(0, x0), min(W, x1)):
            c[y][x] = col

def plot(c, x, y, col):
    if 0 <= x < W and 0 <= y < H: c[y][x] = col

def ship():
    c = canvas()
    # The sea: deep below, with waves and the light on them
    for y in range(14, H):
        for x in range(W):
            c[y][x] = 'b' if (x + 2 * y) % 9 else 'B'
    for x in range(W):
        if (x // 3) % 4 != 1: plot(c, x, 14, 'B')
        if (x + 5) % 11 == 0: plot(c, x, 16, 'C')
        if (x + 1) % 13 == 0: plot(c, x, 18, 'c')
    # The hull: a raked bow on the right, the stern rounded on the left
    for y, x0, x1 in ((10, 5, 67), (11, 6, 66), (12, 7, 64), (13, 9, 62)):
        rect(c, x0, y, x1, y + 1, 'w')
    rect(c, 10, 13, 61, 14, 'r')                # the waterline
    rect(c, 6, 10, 66, 11, 'W')                 # the deck, in the light
    for x in range(14, 60, 4): plot(c, x, 11, 'Y')  # portholes
    # The bow wave and the wake
    for x, y in ((62, 13), (63, 13), (64, 14), (61, 14), (65, 14), (63, 15), (66, 15),
                 (60, 14)):
        plot(c, x, y, 'W')
    for x in range(0, 9): plot(c, x, 14, 'W' if x % 2 else 'C')
    # The superstructure, the bridge, the mast, its yard and radar
    rect(c, 28, 8, 42, 10, 'w')
    rect(c, 30, 6, 40, 8, 'w')
    rect(c, 31, 6, 39, 7, 'W')
    rect(c, 32, 4, 38, 6, 'w')
    rect(c, 33, 4, 37, 5, 'Y')                  # the bridge's windows
    rect(c, 35, 1, 36, 4, 'w')                  # the mast
    rect(c, 33, 2, 38, 3, 'w')
    rect(c, 34, 0, 37, 1, 'W')                  # the radar
    plot(c, 35, 0, 'R')
    # The funnel, and its smoke drifting aft
    rect(c, 22, 5, 26, 10, 'w')
    rect(c, 22, 5, 26, 6, 'r')
    for x, y, col in ((22, 4, 'W'), (23, 4, 'W'), (21, 3, 'W'), (22, 3, 'W'), (20, 3, 'W'),
                      (18, 2, 'W'), (19, 2, 'W'), (17, 2, 'W'), (18, 3, 'W'), (19, 3, 'w'),
                      (14, 1, 'w'), (15, 1, 'W'), (13, 1, 'w'), (14, 2, 'w'), (15, 2, 'w'),
                      (9, 0, 'w'), (10, 0, 'w'), (11, 0, 'w'), (10, 1, 'w'), (5, 0, 'w')):
        plot(c, x, y, col)
    # The turrets and their guns: two forward (one raised), one aft
    rect(c, 47, 8, 53, 10, 'w')
    rect(c, 53, 8, 61, 9, 'W')
    rect(c, 42, 6, 47, 8, 'w')
    rect(c, 47, 6, 54, 7, 'W')
    rect(c, 13, 8, 19, 10, 'w')
    rect(c, 6, 8, 13, 9, 'W')
    # The flag at the stern
    rect(c, 8, 5, 9, 10, 'w')
    rect(c, 9, 5, 12, 7, 'R')
    return c

def c_data(c):
    out = ['// Generated by shipart.py: the title\'s battleship, as pixels, two to a',
           '// character cell (top and bottom), as letters of the palette in',
           '// title.c, row after row in one string (CMOC keeps it in the module).',
           '// @license gpl v. 3, see fujinet/LICENSE for details.',
           '#define SHIP_W %d' % W, '#define SHIP_H %d' % H,
           'static const char ship_art[%d] =' % (W * H + 1)]
    out += ['    "%s"' % ''.join(r) for r in c]
    out[-1] += ';'
    return '\n'.join(out)

def preview(c, path):
    s = 8
    with open(path, 'wb') as f:
        f.write(b'P6 %d %d 255\n' % (W * s, H * s))
        for row in c:
            line = b''.join(bytes(PAL[p] or (0, 0, 0)) * s for p in row)
            f.write(line * s)

if __name__ == '__main__':
    art = ship()
    if sys.argv[1] == 'preview':
        preview(art, 'shipart.ppm')
    else:
        print(c_data(art))
